    private class LocalWebViewClient extends WebViewClient {
        @Override
        public boolean shouldOverrideUrlLoading(WebView view, WebResourceRequest request) {
            Uri uri = request.getUrl();
            String scheme = uri.getScheme() == null ? "" : uri.getScheme();
            if (scheme.equals("http") || scheme.equals("https")) {
                if (isLocalAssetUri(uri)) return false; // our own origin — load in WebView
                handleExternal(uri);
                return true;
            }
            if (scheme.equals("mailto") || scheme.equals("tel") || scheme.equals("sms")
                    || scheme.equals("whatsapp") || scheme.equals("geo") || scheme.equals("market")
                    || scheme.equals("intent")) {
                openExternal(uri);
                return true;
            }
            if (scheme.equals("file") || scheme.equals("data") || scheme.equals("about")
                    || scheme.equals("javascript")) {
                return false;
            }
            // Unknown scheme: attempt external app
            openExternal(uri);
            return true;
        }

        @Override
        public WebResourceResponse shouldInterceptRequest(WebView view, WebResourceRequest request) {
            if (assetLoader != null) {
                WebResourceResponse response = assetLoader.shouldInterceptRequest(request.getUrl());
                if (response != null) return response;
            }
            return super.shouldInterceptRequest(view, request);
        }

        @Override
        public void onPageFinished(WebView view, String url) {
            super.onPageFinished(view, url);
            progressBar.setVisibility(View.GONE);
            if (optBoolean("downloadsEnabled", true)) injectBlobShim(view);
            if (!splashDismissed) {
                splashDismissed = true;
                splashOverlay.animate().alpha(0f).setDuration(300)
                        .withEndAction(new Runnable() {
                            @Override public void run() { splashOverlay.setVisibility(View.GONE); }
                        }).start();
            }
        }

        @Override
        public void onReceivedError(WebView view, WebResourceRequest request, WebResourceError error) {
            if (request.isForMainFrame()) {
                String desc = error.getDescription() == null ? "Unknown error" : error.getDescription().toString();
                showErrorPage(desc, request.getUrl().toString());
            }
        }

        private void showErrorPage(String description, String url) {
            try {
                String html = readAsset("error_offline.html");
                html = html.replace("__ERROR__", android.text.Html.escapeHtml(description))
                           .replace("__URL__", android.text.Html.escapeHtml(url));
                webView.loadDataWithBaseURL(null, html, "text/html", "UTF-8", null);
            } catch (Exception e) {
                Toast.makeText(MainActivity.this, "Page failed to load: " + description, Toast.LENGTH_LONG).show();
            }
        }
    }

    private String readAsset(String name) throws Exception {
        InputStream is = getAssets().open(name);
        ByteArrayOutputStream bos = new ByteArrayOutputStream();
        byte[] buf = new byte[8192];
        int n;
        while ((n = is.read(buf)) > 0) bos.write(buf, 0, n);
        is.close();
        return bos.toString("UTF-8");
    }

